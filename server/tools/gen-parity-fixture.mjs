/**
 * Regenerate `test/parity.fixture.json`.
 *
 * The fixture pins what the JavaScript box office produces for a fixed date.
 * Two test suites read it: `test/parity.test.mjs` (guards the server against
 * drift) and `app/test/parity_test.dart` (guards the Flutter mirror against the
 * server). If you deliberately change a rule in `src/domain.mjs`, run this and
 * commit the new fixture — then both sides move together, or the Dart test
 * fails and tells you which one you forgot.
 *
 *     node tools/gen-parity-fixture.mjs
 */

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { fnv1a, mulberry32, seatMapFor, slotsFor } from "../src/domain.mjs";

const here = dirname(fileURLToPath(import.meta.url));

/** A fixed anchor, so "next 21 days" means the same days in both languages. */
const FROM = "2026-09-01";

const SHOWS = ["lighthouse", "neon-orchestra", "coriolanus"];

const fixture = {
  note: "Generated by server/tools/gen-parity-fixture.mjs. Do not edit by hand.",
  from: FROM,
  prng: {
    // The 32-bit primitives, checked directly so a mismatch points at the
    // arithmetic rather than at the seat rules built on top of it.
    fnv1a: Object.fromEntries(
      ["", "a", "lighthouse", "seatmap:lighthouse:2026-09-05:1200", "ÿ"].map(
        (s) => [s, fnv1a(s)],
      ),
    ),
    mulberry32: (() => {
      const rand = mulberry32(fnv1a("showtime"));
      return Array.from({ length: 8 }, () => Number(rand().toFixed(12)));
    })(),
  },
  shows: {},
};

for (const showId of SHOWS) {
  const slots = slotsFor(showId, { from: new Date(`${FROM}T00:00:00`) });
  const sample = slots.slice(0, 6);

  fixture.shows[showId] = {
    slotCount: slots.length,
    slots: sample.map((slot) => ({
      id: slot.id,
      startsAt: slot.startsAt,
      seatsLeft: slot.seatsLeft,
      tag: slot.tag,
    })),
    // One character per seat: `.` free, `x` taken. Compact and diffable.
    houses: sample.slice(0, 3).map((slot) => ({
      slotId: slot.id,
      rows: seatMapFor(slot.id).rows.map((row) =>
        row.seats.map((seat) => (seat.status === "available" ? "." : "x")).join(""),
      ),
    })),
  };
}

const out = join(here, "../test/parity.fixture.json");
writeFileSync(out, `${JSON.stringify(fixture, null, 2)}\n`);
console.log(`wrote ${out}`);
